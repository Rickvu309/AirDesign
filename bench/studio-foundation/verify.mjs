import assert from "node:assert/strict"
import {mkdir,writeFile} from "node:fs/promises"
import os from "node:os"
import path from "node:path"
import {chromium} from "playwright"
import {stack,seed} from "../design-parity/capture.mjs"

const out=process.env.STUDIO_FOUNDATION_EVIDENCE ?? path.join(os.homedir(),"tmp/airdesign-polish/shell/behavior")
await mkdir(out,{recursive:true})
const local=await stack(),browser=await chromium.launch({headless:true}),checks=[]
try{
  const {owner}=await seed(local,{seed:"recents",code:"shellfix",route:"/"})
  const context=await browser.newContext({viewport:{width:1440,height:923},reducedMotion:"reduce"})
  await context.addCookies(owner.cookie.split("; ").map(pair=>{const index=pair.indexOf("=");return {name:pair.slice(0,index),value:pair.slice(index+1),url:local.origin}}))
  const page=await context.newPage(),errors=[]
  page.on("pageerror",error=>errors.push(String(error)))
  page.setDefaultTimeout(10000)
  await page.clock.setFixedTime(new Date(local.fixture.now()))
  async function capture(name,capturePage=page){
    await capturePage.evaluate(()=>document.fonts.ready)
    const size=await capturePage.evaluate(()=>({viewport:innerWidth,body:document.documentElement.scrollWidth}))
    assert.ok(size.body<=size.viewport,`${name}: horizontal overflow ${JSON.stringify(size)}`)
    assert.deepEqual(errors,[],`${name}: browser errors`)
    await capturePage.screenshot({path:path.join(out,`${name}.png`),fullPage:true})
    checks.push({name,...size,passed:true})
  }
  await page.goto(local.origin)
  await page.getByRole("heading",{name:"Recents",exact:true}).waitFor()
  await page.getByLabel("Account menu",{exact:true}).focus()
  await page.keyboard.press("Tab")
  assert.equal(await page.locator(":focus").getAttribute("aria-label"),"Search")
  const searchResponse=page.waitForResponse(response=>response.url().includes("/api/catalog")&&response.url().includes("search=needle"))
  await page.getByRole("searchbox",{name:"Search",exact:true}).fill("needle")
  await searchResponse
  await page.getByRole("heading",{name:"No decks found",exact:true}).waitFor()
  await page.getByRole("searchbox",{name:"Search",exact:true}).fill("")
  await page.keyboard.press("Tab")
  assert.equal(await page.locator(":focus").textContent(),"Recents")
  await page.keyboard.press("Tab")
  assert.equal(await page.locator(":focus").textContent(),"All decks")
  await page.keyboard.press("Enter")
  await page.getByRole("heading",{name:"All decks",exact:true}).waitFor()
  assert.equal(await page.getByRole("link",{name:"All decks",exact:true}).getAttribute("aria-current"),"page")
  await page.getByRole("button",{name:"List view",exact:true}).click()
  assert.equal(await page.getByRole("button",{name:"List view",exact:true}).getAttribute("aria-pressed"),"true")
  await page.getByRole("link",{name:"Trash",exact:true}).click()
  await page.getByRole("heading",{name:"Trash",exact:true}).waitFor()
  await page.getByRole("link",{name:"Settings",exact:true}).click()
  await page.getByRole("heading",{name:"Settings",exact:true}).waitFor()
  await page.getByRole("link",{name:"Recents",exact:true}).click()
  await page.getByRole("heading",{name:"Recents",exact:true}).waitFor()
  await page.keyboard.press("Control+k")
  await page.getByRole("dialog").waitFor()
  await page.keyboard.press("Escape")
  await capture("shell-1440")
  for(const mobile of [false,true]){
    const searchContext=await browser.newContext({viewport:mobile ? {width:390,height:844} : {width:1440,height:923},isMobile:mobile,hasTouch:mobile,reducedMotion:"reduce"})
    try{
      await searchContext.addCookies(owner.cookie.split("; ").map(pair=>{const index=pair.indexOf("=");return {name:pair.slice(0,index),value:pair.slice(index+1),url:local.origin}}))
      const searchPage=await searchContext.newPage()
      searchPage.on("pageerror",error=>errors.push(String(error)))
      const field=searchPage.getByRole("searchbox",{name:"Search",exact:true})
      for(const destination of ["/settings/usage","/settings/agents","/settings/account","/trash"]){
        await searchPage.goto(local.origin+destination)
        if(mobile)await field.tap();else await field.focus()
        await field.pressSequentially("Strategy")
        await searchPage.getByRole("heading",{name:"All decks",exact:true}).waitFor()
        await searchPage.locator(".deck-card").filter({hasText:"Pricing Strategy Review"}).waitFor()
        assert.equal(new URL(searchPage.url()).pathname,"/")
        assert.equal(await field.inputValue(),"Strategy")
        assert.equal(await field.evaluate(element=>element===document.activeElement),true)
        assert.equal(await searchPage.locator(".deck-card").count(),1)
        await capture(`search-${destination.split("/").at(-1)}-${mobile ? "touch-390" : "1440"}`,searchPage)
      }
      for(const [name,href] of [["Recents","/"],["All decks","/?browse=all"],["Trash","/trash"],["Settings","/settings/usage"]])assert.equal(await searchPage.getByRole("link",{name,exact:true}).getAttribute("href"),href)
      if(!mobile){
        const popup=searchContext.waitForEvent("page")
        await searchPage.getByRole("link",{name:"Settings",exact:true}).click({modifiers:["Control"]})
        const tab=await popup
        await tab.waitForLoadState()
        assert.equal(new URL(tab.url()).pathname,"/settings/usage")
        await tab.close()
        assert.equal(await field.inputValue(),"Strategy")
      }
    }finally{await searchContext.close()}
  }
  await page.setViewportSize({width:390,height:844})
  await capture("shell-390")
  await page.getByLabel("Account menu",{exact:true}).click()
  await page.getByRole("button",{name:"Sign out",exact:true}).click()
  await page.getByRole("dialog").waitFor()
  await capture("sign-out-dialog-390")
  await page.getByRole("button",{name:"Cancel",exact:true}).click()
  assert.equal(await page.locator(":focus").getAttribute("aria-label"),"Account menu")
  await page.getByLabel("Account menu",{exact:true}).click()
  await page.getByRole("button",{name:"Sign out",exact:true}).click()
  await page.getByRole("dialog").getByRole("button",{name:"Sign out",exact:true}).click()
  await page.locator('[data-screen="signin"]').waitFor()
  await capture("sign-in-390")
  await page.getByLabel("Email",{exact:true}).fill("foundation@example.com")
  await page.getByLabel("Email",{exact:true}).press("Enter")
  await page.getByRole("heading",{name:"Check your email",exact:true}).waitFor()
  const accessHeader=await page.locator(".ad-access-header").boundingBox()
  assert.ok(accessHeader&&accessHeader.y>=64,"code-entry focus keeps the phone access header visible")
  const cardGap=await page.locator(".ad-check-card").evaluate(element=>getComputedStyle(element).rowGap)
  assert.equal(cardGap,"22px")
  await capture("check-email-390")
  await page.setViewportSize({width:1440,height:923})
  await capture("check-email-1440")
  const inbox=await local.request(null,"/api/dev/inbox?to=foundation%40example.com")
  const code=inbox.messages.at(-1).code,wrong=code==="000000" ? "111111" : "000000"
  for (const [index,digit] of [...wrong].entries()) await page.locator(".ad-code-box").nth(index).fill(digit)
  await page.locator('[data-screen="expired"]').waitFor()
  await capture("wrong-code-1440")
  await page.getByRole("button",{name:"Send a new link",exact:true}).click()
  assert.equal(await page.getByLabel("Email",{exact:true}).inputValue(),"foundation@example.com")
  local.fixture.advance(31000)
  await page.clock.setFixedTime(new Date(local.fixture.now()))
  await page.getByLabel("Email",{exact:true}).press("Enter")
  await page.locator('[data-screen="check"]').waitFor()
  const latest=await local.request(null,"/api/dev/inbox?to=foundation%40example.com")
  local.fixture.advance(16*60*1000)
  for (const [index,digit] of [...latest.messages.at(-1).code].entries()) await page.locator(".ad-code-box").nth(index).fill(digit)
  await page.locator('[data-screen="expired"]').waitFor()
  await page.setViewportSize({width:390,height:844})
  await capture("expired-code-390")
  await context.close()
  const touchOwner=await local.fixture.signIn("mobile-foundation-owner@example.com")
  const touch=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:"reduce"})
  await touch.addCookies(touchOwner.cookie.split("; ").map(pair=>{const index=pair.indexOf("=");return {name:pair.slice(0,index),value:pair.slice(index+1),url:local.origin}}))
  const phone=await touch.newPage()
  phone.on("pageerror",error=>errors.push(String(error)))
  await phone.clock.setFixedTime(new Date(local.fixture.now()))
  await phone.goto(local.origin)
  await phone.getByRole("heading",{name:"Recents",exact:true}).waitFor()
  assert.equal(await phone.evaluate(()=>matchMedia("(pointer: coarse)").matches),true)
  const search=phone.getByRole("searchbox",{name:"Search",exact:true})
  assert.ok(await search.evaluate(element=>parseFloat(getComputedStyle(element).fontSize)>=16),"touch search does not trigger input zoom")
  for(const name of ["Recents","All decks","Trash","Settings","New deck","Grid view","List view"]){
    const bounds=await phone.getByRole(["Recents","All decks","Trash","Settings"].includes(name) ? "link" : "button",{name,exact:true}).boundingBox()
    assert.ok(bounds&&bounds.width>=44&&bounds.height>=44,`${name}: touch target`)
  }
  await capture("shell-touch-390",phone)
  await phone.getByLabel("Account menu",{exact:true}).tap()
  await phone.getByRole("button",{name:"Sign out",exact:true}).tap()
  await phone.getByRole("dialog").waitFor()
  await capture("sign-out-dialog-touch-390",phone)
  await phone.getByRole("dialog").getByRole("button",{name:"Sign out",exact:true}).tap()
  await phone.locator('[data-screen="signin"]').waitFor()
  assert.ok(await phone.getByLabel("Email",{exact:true}).evaluate(element=>parseFloat(getComputedStyle(element).fontSize)>=16),"touch email does not trigger input zoom")
  await capture("sign-in-touch-390",phone)
  await phone.getByLabel("Email",{exact:true}).fill("touch-foundation@example.com")
  await phone.getByRole("button",{name:"Continue",exact:true}).tap()
  await phone.locator('[data-screen="check"]').waitFor()
  await capture("check-email-touch-390",phone)
  const touchHeader=await phone.locator(".ad-access-header").boundingBox()
  assert.ok(touchHeader&&touchHeader.y>=64,"touch code focus preserves the access header")
  const touchInbox=await local.request(null,"/api/dev/inbox?to=touch-foundation%40example.com")
  const touchCode=touchInbox.messages.at(-1).code
  const touchWrong=touchCode==="000000" ? "111111" : "000000"
  for(const [index,digit] of [...touchWrong].entries()) await phone.locator(".ad-code-box").nth(index).fill(digit)
  await phone.locator('[data-screen="expired"]').waitFor()
  await capture("expired-code-touch-390",phone)
  await touch.close()
  await writeFile(path.join(out,"report.json"),JSON.stringify({passed:true,checks},null,2)+"\n")
  process.stdout.write(`PASS ${checks.length} browser captures; keyboard navigation, search, view toggle, command menu, sign-out, recovery and 390px overflow\n`)
}finally{await browser.close();await local.close()}
