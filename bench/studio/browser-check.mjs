import assert from "node:assert/strict"
import { chromium,expect } from "playwright/test"
import { localStack,signIn } from "../sync/local-stack.mjs"
import { newSlide } from "../../apps/studio/src/editor/editor-model.ts"

export async function runStudio(browser,stack) {
const context=await browser.newContext({viewport:{width:1440,height:1000}})
try {
 await signIn(context,stack.origin,"manual-studio@example.com")
 const page=await context.newPage(),headers={origin:stack.origin}
 await page.goto(stack.origin)
 await expect(page.getByRole("button",{name:"Scratchpad Your first draft",exact:true})).toBeVisible()
 assert.equal(await page.locator(".deck-starter").count(),2)
 await page.getByRole("button",{name:"New deck",exact:true}).click()
 await page.getByRole("button",{name:"Blank deck",exact:true}).click()
 await page.locator('[data-sync-state="saved"]').waitFor()
 const deck=page.url().split("/").at(-1)
 await page.getByLabel("Your first request").fill("Explain our quarterly strategy")
 await expect(page.getByRole("button",{name:"Build with Aira",exact:true})).toBeEnabled()
 await page.reload()
 await expect(page.getByLabel("Your first request")).toHaveValue("Explain our quarterly strategy")
 await page.getByRole("button",{name:"New slide",exact:true}).click()
 await expect(page.locator('[contenteditable="true"]')).toHaveCount(0)
 await page.getByRole("button",{name:"Single slide view",exact:true}).click()
 await page.getByRole("textbox",{name:"Text · Add your title",exact:true}).fill("A clearer story")
 await page.locator('[data-sync-state="saved"]').waitFor()
 await page.getByRole("button",{name:"Slide 1",exact:true}).click()
 await page.getByLabel("Speaker notes",{exact:true}).fill("Person notes")
 await page.locator('[data-sync-state="saved"]').waitFor()
 await expect(page.locator(".ad-topbar")).toHaveCount(0)
 await expect(page.getByRole("navigation",{name:"Design tools"})).toBeVisible()
 await expect(page.getByRole("button",{name:"Agent",exact:true})).toBeEnabled()
 await expect(page.locator(".studio-editor")).toHaveAttribute("data-view","single")
 await page.getByRole("button",{name:"Grid view",exact:true}).click()
 await expect(page.locator(".studio-editor")).toHaveAttribute("data-view","grid")
 await page.getByRole("button",{name:"Single slide view",exact:true}).click()
 await page.getByRole("navigation",{name:"Edit history",exact:true}).getByRole("button",{name:"Undo",exact:true}).click()
 await expect(page.getByLabel("Speaker notes",{exact:true})).toHaveValue("")
 await page.getByRole("navigation",{name:"Edit history",exact:true}).getByRole("button",{name:"Redo",exact:true}).click()
 await expect(page.getByLabel("Speaker notes",{exact:true})).toHaveValue("Person notes")
 await page.locator(".deck-name").click()
 await page.getByRole("button",{name:"Review changes",exact:true}).click()
 await expect(page.locator(".editor-changes li").first()).toContainText("You:")
 await page.getByText("Changes by slide",{exact:true}).click()
 await page.locator(".deck-name").click()
 await page.getByRole("button",{name:"Paste slides",exact:true}).click()
 const source=JSON.stringify({slides:[newSlide(),{id:"broken"}]})
 await page.getByLabel("Original slide JSON",{exact:true}).fill(source)
 await page.getByRole("button",{name:"Review paste",exact:true}).click()
 await expect(page.getByRole("dialog")).toContainText("1 slides accepted")
 await page.getByRole("button",{name:"Cancel",exact:true}).click()
 await expect(page.getByLabel("Original slide JSON",{exact:true})).toHaveValue(source)
 await page.getByRole("button",{name:"Review paste",exact:true}).click()
 await page.getByRole("button",{name:"Insert accepted slides",exact:true}).click()
 await expect(page.locator(".editor-slide")).toHaveCount(2)
 await page.locator('[data-sync-state="saved"]').waitFor()
 await page.getByRole("button",{name:"Grid view",exact:true}).click()
 await page.getByRole("button",{name:"Slide 1",exact:true}).click()
 await page.getByRole("button",{name:"Slide 2",exact:true}).click({modifiers:["Shift"]})
 await expect(page.locator('.editor-slide[data-selected="true"]')).toHaveCount(2)
 await page.goto(stack.origin)
 await page.locator("article.deck-card").waitFor()
 await page.getByRole("button",{name:/^Actions for /}).click()
 await page.getByRole("button",{name:"Rename",exact:true}).click()
 await page.getByLabel("Deck name",{exact:true}).fill("Quarterly strategy")
 await page.getByRole("button",{name:"Save name",exact:true}).click()
 await expect(page.locator(".deck-card h2")).toHaveText("Quarterly strategy")
 await page.getByRole("searchbox",{name:"Search",exact:true}).fill("nothing matches %_")
 await expect(page.getByRole("heading",{name:"No decks found",exact:true})).toBeVisible()
 await expect(page.getByRole("searchbox",{name:"Search",exact:true})).toHaveValue("nothing matches %_")
 await page.getByRole("searchbox",{name:"Search",exact:true}).fill("")
 await page.locator("article.deck-card").waitFor()
 await page.getByRole("button",{name:/^Actions for /}).click()
 await page.getByRole("button",{name:"Duplicate",exact:true}).click()
 await expect(page.locator(".deck-card")).toHaveCount(2)
 const phone=await context.newPage();await phone.setViewportSize({width:320,height:760})
 await phone.goto(`${stack.origin}/deck/${deck}`)
 await expect(phone.getByRole("status").filter({hasText:"Edit on a laptop"})).toBeVisible()
 assert.equal(await phone.locator('[contenteditable="true"]').count(),0)
 assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth<=320),true)
 await phone.locator(".deck-name").click()
 assert.equal(await phone.evaluate(()=>{
  const menu=document.querySelector(".editor-menu"),bar=document.querySelector(".editor-export")
  const a=menu.getBoundingClientRect(),b=bar.getBoundingClientRect(),x=Math.max(a.left,b.left)+1,y=Math.max(a.top,b.top)+1
  return x>=Math.min(a.right,b.right)||y>=Math.min(a.bottom,b.bottom)||menu.contains(document.elementFromPoint(x,y))
 }),true,"deck-menu-above-export-at-320")
 await phone.close()
 const stale=await context.newPage()
 await stale.goto(`${stack.origin}/deck/${deck}`)
 await stale.locator('[data-sync-state="saved"]').waitFor()
 await stale.getByRole("button",{name:"Single slide view",exact:true}).click()
 const canonicalText=await stale.locator('[data-text]').allTextContents()
 await stale.setViewportSize({width:320,height:760})
 await expect(stale.getByRole("status").filter({hasText:"Edit on a laptop"})).toBeVisible()
 assert.deepEqual(await stale.locator('[data-text]').allTextContents(),canonicalText,"Phone transition keeps canonical text exactly once")
 await stale.setViewportSize({width:1440,height:1000})
 await expect(stale.locator('[contenteditable="true"]').first()).toBeVisible()
 assert.deepEqual(await stale.locator('[data-text]').allTextContents(),canonicalText,"Desktop transition restores canonical editable text")
 assert.equal((await context.request.post(`${stack.origin}/api/catalog/${deck}/trash`,{headers,data:{}})).status(),200)
 await stale.locator('[data-sync-state="deleted"]').waitFor()
 await expect(stale.getByRole("button",{name:"New slide",exact:true})).toBeDisabled()
 await stale.reload()
 await stale.locator('[data-sync-state="deleted"]').waitFor()
 const restored=stale.waitForResponse(response=>response.url().endsWith(`/api/catalog/${deck}/restore`))
 await stale.getByRole("button",{name:"Restore deck",exact:true}).click()
 const restoreResponse=await restored;assert.equal(restoreResponse.status(),200)
 await stale.locator('[data-sync-state="saved"]').waitFor()
 await stale.close()
 const read=await (await context.request.get(`${stack.origin}/api/decks/${deck}`)).json()
 assert.equal(read.deck.slides.length,2)
 assert.equal(read.deck.slides[0].notes,"Person notes")
 return {verdict:"pass",deck,sequence:read.seq,slides:2,phoneWidth:320,pasteRetained:true}
}finally{await context.close()}
}
if(import.meta.url===`file://${process.argv[1]}`){const stack=await localStack(),browser=await chromium.launch();try{process.stdout.write(JSON.stringify(await runStudio(browser,stack))+"\n")}finally{await browser.close();await stack.close()}}
