  "Fix it.\n\nGenerated with [Claude Code](https://claude.ai/code)\n",
  "Fix it.\n\n\u{1F916} Generated with [Claude Code](https://claude.ai/code)\n",
  "Fix it.\n\ngenerated with codex\n",
  "Fix it.\n\nGenerated by Grok\n",
  "Fix it.\n\nGenerated-by: Copilot\n",
