// Extracts a curated, deduplicated icon set from the generated snapshot icons into ui-pack/src/kit/icon-data.ts.
// Every kit icon is single-colour (currentColor), so it follows the text colour of its parent.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const icons = join(root, "ui-pack/src/icons");
const out = join(root, "ui-pack/src/kit");
mkdirSync(out, { recursive: true });

// kit name -> snapshot component it is taken from
const picks = {
  search: "SearchIcon", close: "ShareCloseIcon", plus: "GettingStartedPlusIcon", "add-circle": "GettingStartedAddCircleIcon",
  "chevron-down": "GettingStartedChevronDownIcon", "chevron-right": "ShareChevronRightIcon", "chevron-left": "TextChevronLeftIcon",
  more: "AgentsMoreIcon", trash: "TrashIcon", settings: "SettingsIcon", clock: "ClockIcon", file: "HomeFileIcon", bell: "NotificationBellIcon",
  play: "SharePlayIcon", upload: "UploadIcon", globe: "GlobeIcon", palette: "PaletteIcon", image: "ImageIcon", table: "TableIcon",
  list: "ListIcon", grid: "HomeGridSmallIcon", layout: "HomeLayoutIcon", sparkle: "HomeSparkleIcon", frame: "GettingStartedFrameIcon",
  code: "CodeBlockIcon", cursor: "CursorIcon", hand: "HandIcon", text: "GettingStartedTextIcon", comment: "GettingStartedCommentIcon",
  move: "GettingStartedMoveIcon", pen: "GettingStartedPenIcon", rectangle: "GettingStartedRectangleIcon", shapes: "GettingStartedShapesIcon",
  "image-video": "GettingStartedImageVideoIcon", actions: "GettingStartedActionsIcon", "copy-link": "ShareCopyLinkIcon",
  help: "GettingStartedHelpIcon", resources: "ResourcesIcon", "slide-view": "MediaSlideViewIcon", present: "PresentIcon",
  adjust: "AdjustIcon", "slide-number": "SlideNumberIcon", menu: "GettingStartedMainMenuIcon", "arrow-up": "ArrowUpIcon",
};

const data = {};
const skipped = [];
for (const [name, comp] of Object.entries(picks)) {
  let src;
  try { src = readFileSync(join(icons, `${comp}.tsx`), "utf8"); } catch { skipped.push(`${name}: ${comp} missing`); continue; }
  const vb = src.match(/viewBox="([^"]*)"/)?.[1];
  const paths = [...src.matchAll(/<path\b([\s\S]*?)><\/path>/g)].map((m) => {
    const d = m[1].match(/ d="([^"]*)"/)?.[1];
    const fill = m[1].match(/"fill": "([^"]*)"/)?.[1] ?? "";
    return { d, fill, evenodd: /fillRule="evenodd"/.test(m[1]) };
  });
  const ink = (f) => /--ad-icon|--ad-ink|--ad-surface/.test(f) || /^rgba?\((0, 0, 0|255, 255, 255)/.test(f);
  if (!vb || !paths.length || paths.some((p) => !p.d) || src.includes("<circle") || src.includes("<rect") || !paths.every((p) => ink(p.fill))) {
    skipped.push(`${name}: ${comp} is not a plain single-colour icon`);
    continue;
  }
  data[name] = { viewBox: vb, paths: paths.map((p) => (p.evenodd ? { d: p.d, evenodd: true } : { d: p.d })) };
}
writeFileSync(
  join(out, "icon-data.ts"),
  `// Generated by scripts/build-ui-kit-icons.mjs. Do not edit.
export interface IconShape { viewBox: string; paths: { d: string; evenodd?: boolean }[] }
export const iconData = ${JSON.stringify(data, null, 1)} as const satisfies Record<string, IconShape>;
export type IconName = keyof typeof iconData;
`,
);
console.log(`kit icons: ${Object.keys(data).length}`, skipped.length ? `\nskipped:\n${skipped.join("\n")}` : "");
