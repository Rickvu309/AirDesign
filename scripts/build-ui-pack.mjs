// Rebuild ui-pack/src from lunagraph/components/airdesign (components only, no compositions).
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const from = join(root, "lunagraph/components/airdesign");
const to = join(root, "ui-pack/src");
rmSync(to, { recursive: true, force: true });
mkdirSync(to, { recursive: true });

const groups = readdirSync(from)
  .filter((f) => f.endsWith(".tsx") && !f.endsWith(".compositions.tsx"))
  .map((f) => f.replace(/\.tsx$/, ""))
  .sort();

const seen = new Map();
const names = new Map();
let total = 0;
for (const g of groups) {
  const src = readFileSync(join(from, `${g}.tsx`), "utf8");
  writeFileSync(join(to, `${g}.tsx`), src);
  for (const m of src.matchAll(/^export function (\w+)/gm)) {
    if (seen.has(m[1])) throw new Error(`duplicate export ${m[1]} in ${g} and ${seen.get(m[1])}`);
    seen.set(m[1], g);
    names.set(g, [...(names.get(g) ?? []), m[1]]);
    total++;
  }
}
const barrel = [
  "// Generated by scripts/build-ui-pack.mjs. Do not edit.",
  `export type { AirDesignComponentProps } from "./${groups[0]}.tsx";`,
  ...groups.map((g) => `export { ${names.get(g).join(", ")} } from "./${g}.tsx";`),
  "",
].join("\n");
writeFileSync(join(to, "index.ts"), barrel);
console.log(`ui-pack: ${groups.length} groups, ${total} components`);
