// Rebuild ui-pack/src from lunagraph/components/airdesign (components only, no compositions).
// One file per component: src/<group>/<Name>.tsx, plus src/types.ts and a src/index.ts barrel.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const from = join(root, "lunagraph/components/airdesign");
const to = join(root, "ui-pack/src");
rmSync(to, { recursive: true, force: true });
mkdirSync(to, { recursive: true });

writeFileSync(join(to, "types.ts"), `import type { CSSProperties } from "react";

export interface AirDesignComponentProps {
  style?: CSSProperties;
  className?: string;
}
`);

const groups = readdirSync(from)
  .filter((f) => f.endsWith(".tsx") && !f.endsWith(".compositions.tsx"))
  .map((f) => f.replace(/\.tsx$/, ""))
  .sort();

const seen = new Set();
const lines = ["// Generated by scripts/build-ui-pack.mjs. Do not edit.", 'export type { AirDesignComponentProps } from "./types.ts";'];
for (const g of groups) {
  const src = readFileSync(join(from, `${g}.tsx`), "utf8");
  const chunks = src.split(/^(?=export function )/m).filter((c) => c.startsWith("export function "));
  mkdirSync(join(to, g), { recursive: true });
  for (const c of chunks) {
    const name = c.match(/^export function (\w+)/)[1];
    if (seen.has(name)) throw new Error(`duplicate component ${name}`);
    seen.add(name);
    const needsCss = /CSSProperties/.test(c);
    const head = (needsCss ? 'import type { CSSProperties } from "react";\n' : "") + 'import type { AirDesignComponentProps } from "../types.ts";\n\n';
    writeFileSync(join(to, g, `${name}.tsx`), head + c.trimEnd() + "\n");
    lines.push(`export { ${name} } from "./${g}/${name}.tsx";`);
  }
}
writeFileSync(join(to, "index.ts"), lines.join("\n") + "\n");
console.log(`ui-pack: ${groups.length} groups, ${seen.size} components`);
