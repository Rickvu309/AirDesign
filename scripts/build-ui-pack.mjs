// Rebuild ui-pack/src from lunagraph/components/airdesign (components only, no compositions).
// One file per component: src/<group>/<Name>.tsx, plus src/types.ts and a src/index.ts barrel.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { transform, TOKENS } from "./ui-pack-transforms.mjs";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const from = join(root, "lunagraph/components/airdesign");
const to = join(root, "ui-pack/src");
mkdirSync(to, { recursive: true });
// src/kit is hand-written; everything else in src is generated.
for (const f of readdirSync(to)) if (f !== "kit") rmSync(join(to, f), { recursive: true, force: true });

writeFileSync(join(to, "types.ts"), `import type React from "react";
import type { CSSProperties } from "react";

export interface AirDesignComponentProps {
  style?: CSSProperties;
  className?: string;
}

/** Native props of the root element (onClick, ref, aria-*, data-*, ...) plus style and className. */
export type AirDesignProps<Tag extends keyof React.JSX.IntrinsicElements> = React.ComponentProps<Tag>;
`);
writeFileSync(join(to, "tokens.css"), `/* AirDesign design tokens. Override any of these on :root or a parent element. */
:root {
${TOKENS.map(([n, v, d]) => `  --ad-${n}: ${v}; /* ${d} */`).join("\n")}
  --ad-icon: var(--ad-ink); /* Default icon fill */
}
`);

writeFileSync(join(to, "base.css"), `/* Minimal reset the components were designed against (zero specificity; inline styles still win). */
:where(button, input, select, textarea) { margin: 0; font: inherit; color: inherit; background: transparent; border: 0 solid; }
:where(button) { cursor: pointer; }
:where(h1, h2, h3, h4, p, ul, ol, figure) { margin: 0; }
:where(ul, ol) { padding: 0; list-style: none; }
:where(a) { color: inherit; text-decoration: none; }
:where(img, svg) { display: block; }
`);

const groups = readdirSync(from)
  .filter((f) => f.endsWith(".tsx") && !f.endsWith(".compositions.tsx"))
  .map((f) => f.replace(/\.tsx$/, ""))
  .sort();

const seen = new Set();
const lines = ["// Generated by scripts/build-ui-pack.mjs. Do not edit.", 'export type { AirDesignComponentProps, AirDesignProps } from "./types.ts";'];
for (const g of groups) {
  const src = readFileSync(join(from, `${g}.tsx`), "utf8");
  const chunks = src.split(/^(?=export function )/m).filter((c) => c.startsWith("export function "));
  mkdirSync(join(to, g), { recursive: true });
  for (const c of chunks) {
    const name = c.match(/^export function (\w+)/)[1];
    if (seen.has(name)) throw new Error(`duplicate component ${name}`);
    seen.add(name);
    const needsCss = /CSSProperties/.test(c);
    const head = (needsCss ? 'import type { CSSProperties } from "react";\n' : "") + 'import type { AirDesignComponentProps } from "../types.ts";\n\n';
    writeFileSync(join(to, g, `${name}.tsx`), transform(head + c.trimEnd() + "\n", name));
    lines.push(`export { ${name} } from "./${g}/${name}.tsx";`);
  }
}
lines.push('export * from "./kit/index.ts";');
writeFileSync(join(to, "index.ts"), lines.join("\n") + "\n");
console.log(`ui-pack: ${groups.length} groups, ${seen.size} components`);
