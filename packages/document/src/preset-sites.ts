export const siteLimit = 8

export function siteSpot(
  preset: Preset,
  width: number,
  height: number,
  adjust: Readonly<Record<string, number>>,
  site: number,
): Spot | null {
  const rule = siteRules[preset]
  const [x, y] = rule.sites[site]?.split(" ") ?? []
  if (x === undefined || y === undefined) return null
  const value = presetGuides(rule, width, height, adjust)
  return { x: value(x), y: value(y) }
}
