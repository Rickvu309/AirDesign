function shared(mark: string): number {
  const code = mark.charCodeAt(0)
  return code >= 97 ? code - 97 : code - 39
}

function unpacked(): readonly string[] {
  const names: string[] = []
  let last = ""
  for (const entry of packed.split(" ")) {
    last = last.slice(0, shared(entry)) + entry.slice(1)
    names.push(last)
  }
  return names
}

