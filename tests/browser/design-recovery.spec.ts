import { expect, test } from "@playwright/test"
import { designing, openDeck, storedRows, unfold } from "./design-panel"

test("keeps a pasted Name and its suffix until it fits, without sending a change", async ({ page, context }) => {
  await openDeck(page, "clean.pptx")
  const panel = await designing(page, page.locator('[data-slide-paint] [contenteditable="true"]'))
  await unfold(panel, "Name and alt text")
  const name = panel.getByRole("textbox", { name: "Name", exact: true })
  const full = "A".repeat(199) + "Z"
  await name.fill(full)
  await name.press("Enter")
  await expect.poll(async () => JSON.stringify(await storedRows(page))).toContain(full)
  const before = await storedRows(page)
  await name.press("Home")
  await page.keyboard.insertText("X")
  await expect(name).toHaveValue("X" + full)
  await expect(name).toHaveAttribute("aria-invalid", "true")
  await expect(name).toHaveAccessibleDescription("Use 200 characters or fewer.")
  await name.press("Enter")
  await name.press("Tab")
  expect(await storedRows(page)).toEqual(before)
  await expect(name).toHaveValue("X" + full)
  await context.grantPermissions(["clipboard-read", "clipboard-write"])
  const pasted = "é".repeat(101) + "suffix"
  await page.evaluate((text) => navigator.clipboard.writeText(text), pasted)
  await name.focus()
  await name.press("ControlOrMeta+a")
  await name.press("ControlOrMeta+v")
  await expect(name).toHaveValue(pasted)
  await expect(name).toHaveAccessibleDescription("Use 200 characters or fewer. Some letters and emoji count as 2 to 4.")
  await name.press("Enter")
  await name.press("Tab")
  expect(await storedRows(page)).toEqual(before)
  await expect(page.locator("[data-sonner-toast]")).toHaveCount(0)
  await name.fill("Corrected name")
  await name.press("Enter")
  await expect(name).not.toHaveAttribute("aria-invalid", "true")
  await expect.poll(async () => JSON.stringify(await storedRows(page))).toContain("Corrected name")
})
