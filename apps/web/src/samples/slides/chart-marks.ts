import type * as doom from "@airdesign/doom"
import { box, frame, solid } from "../slide-kit.js"

type Props = Exclude<NonNullable<doom.TreeNode["props"]>, (...args: never[]) => unknown>
type Box = ReturnType<typeof box>

function shape(name: string, box: Box, props: Props): doom.TreeNode {
  return { type: "shape", name, props: { box, ...props } }
}

function label(
  name: string,
  box: Box,
  chars: string,
  span: Omit<doom.Span, "end">,
  align: doom.Para["align"],
  style: doom.TextStyleName,
  wrap: doom.Text["wrap"],
  fill?: doom.Color,
): doom.TreeNode {
  return shape(name, box, {
    geometry: { kind: "rect" },
    ...(fill === undefined ? {} : { fills: [solid(fill)] }),
    text: {
      chars,
      spans: [{ ...span, end: chars.length }],
      paras: [align === undefined ? {} : { align }],
      style,
      resize: "fixed",
      alignV: "center",
      ...(wrap === undefined ? {} : { wrap }),
    },
  })
}

function line(
  name: string,
  box: Box,
  start: doom.End,
  end: doom.End,
  color: doom.Color,
  weight: number,
): doom.TreeNode {
  return shape(name, box, {
    geometry: { kind: "line", start, end, route: "straight", arrows: ["none", "none"] },
    strokes: [solid(color)],
    stroke: { weight, align: "center", dash: "solid" },
  })
}

