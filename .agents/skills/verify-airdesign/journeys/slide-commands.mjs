import { expect } from "@playwright/test"
import { newBlankDeck } from "../bin/new-deck.mjs"

export default async function drive({ page, signIn, post, capture, note, deckRoutes }) {
  const { cookie } = await signIn()
  await page.goto("/")
  await newBlankDeck(page)
  await expect(page).toHaveURL(/\/deck\/[A-Za-z0-9_-]{1,64}$/)
  const deck = page.url().split("/").at(-1)
  const entries = page.locator("[data-slide-entry]")
  const entry = (number) => page.locator(`[data-slide-entry="${String(number)}"]`)
  const order = async () => (await post(deckRoutes.open, { deck }, cookie)).json.register.order ?? []
  await expect(entries).toHaveCount(1)
  await page.getByRole("button", { name: "Add slide" }).first().click()
  await expect(entries).toHaveCount(2)
  await page.getByRole("button", { name: "Add text box", exact: true }).click()
  const title = page.locator('[data-slide-paint] [contenteditable="true"]').first()
  await expect(title).toBeFocused()
  await title.pressSequentially("Second slide", { delay: 30 })
  await page.keyboard.press("Escape")
  await expect(entry(2)).toContainText("Second slide")
  await capture("added-and-typed")
  await entry(2).click()
  await page.keyboard.press("ControlOrMeta+d")
  await expect(entries).toHaveCount(3)
  await expect(entry(3)).toContainText("Second slide")
  await capture("duplicated")
  await entry(3).click()
  await page.keyboard.press("Alt+ArrowUp")
  await expect(entry(2)).toHaveAttribute("aria-current", "true")
  await entry(2).click()
  await page.keyboard.press("Alt+ArrowUp")
  await expect(entry(1)).toContainText("Second slide")
  await capture("moved-to-top")
  await entry(1).click()
  await page.keyboard.press("Delete")
  await expect(entries).toHaveCount(2)
  await expect(page.getByRole("button", { name: "Undo delete slide" })).toBeEnabled()
  await capture("deleted")
  await page.keyboard.press("ControlOrMeta+z")
  await expect(entries).toHaveCount(3)
  await expect(page.getByRole("button", { name: "Redo delete slide" })).toBeEnabled()
  await page.getByRole("button", { name: "Redo delete slide" }).click()
  await expect(entries).toHaveCount(2)
  await capture("undone-and-redone")
  await expect
    .poll(async () => (await order()).map((row) => row.slide))
    .toEqual(expect.arrayContaining(["add", "clone", "remove"]))
  const kinds = (await order()).map((row) => row.slide)
  note(`slide order rows on the server: ${kinds.join(", ")}`)
  await page.reload()
  await expect(entries).toHaveCount(2)
  await expect(entry(2)).toContainText("Second slide")
  await capture("reloaded")
  note(
    "Add slide, typing on the new slide, Ctrl/Cmd+D on a slide entry, Alt+ArrowUp on the moved slide twice, Delete on the entry, Ctrl/Cmd+Z and the Redo button all painted at once; the server kept the order and a reload showed two slides with the copy second.",
  )
}
