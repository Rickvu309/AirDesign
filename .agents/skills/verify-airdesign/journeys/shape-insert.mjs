import { undoCopy } from "../bin/product-copy.mjs"
import path from "node:path"
import { expect } from "@playwright/test"
import { importTitleDeck } from "../bin/new-deck.mjs"

const slide = "ppt/slides/slide1.xml"

export default async function drive({ page, signIn, post, capture, note, deckRoutes }) {
  const { cookie } = await signIn()
  await page.goto("/")
  await importTitleDeck(page)
  await expect(page).toHaveURL(/\/deck\/[A-Za-z0-9_-]{1,64}$/)
  const deck = page.url().split("/").at(-1)
  await expect(page.locator(".thin-page")).toHaveAttribute("data-deck-ready", deck)
  const element = (shape) => page.locator(`[data-slide-paint] [data-canvas-element="${slide}#${shape}"]`)
  const painted = (shape) => element(shape).locator("[data-canvas-line]")
  const insert = async (name) => {
    await page.getByRole("button", { name: "Shapes", exact: true }).click()
    await page.getByRole("button", { name, exact: true }).click()
    await page.keyboard.press("Enter")
  }
  await page.getByRole("button", { name: "Shapes", exact: true }).click()
  await expect(page.locator("[data-shape-tray]")).toBeVisible()
  await capture("shape-tray")
  await page.getByRole("button", { name: "Rectangle", exact: true }).click()
  await page.keyboard.press("Enter")
  await expect(page.locator("[data-shape-tray]")).toHaveCount(0)
  await expect(element(4)).toBeVisible()
  await insert("Ellipse")
  await expect(element(5)).toBeVisible()
  await insert("Line")
  await expect(painted(6)).toBeVisible()
  await capture("shape-added")
  const placed = await element(4).boundingBox()
  await element(4).click()
  await expect(page.locator("[data-slide-paint] [data-selection]")).toHaveCount(1)
  await page.keyboard.press("Shift+ArrowRight")
  await expect.poll(async () => (await element(4).boundingBox())?.x ?? 0).toBeGreaterThan((placed?.x ?? 0) + 5)
  const grip = await page.locator('[data-selection] [data-grip="bottom-right"]').boundingBox()
  if (grip === null) throw new Error("no grip")
  await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2)
  await page.mouse.down()
  await page.mouse.move(grip.x + 80, grip.y + 40, { steps: 6 })
  await page.mouse.up()
  await expect.poll(async () => (await element(4).boundingBox())?.width ?? 0).toBeGreaterThan((placed?.width ?? 0) + 40)
  await capture("shape-resized")
  const line = await painted(6).boundingBox()
  if (line === null) throw new Error("no line")
  await page.mouse.click(line.x + line.width / 2, line.y + line.height / 2)
  await expect(page.locator("[data-slide-paint] [data-selection]")).toHaveCount(1)
  await page.keyboard.press("Delete")
  await expect(element(6)).toHaveCount(0)
  await page.getByRole("button", { name: undoCopy.undoNamed["delete-element"], exact: true }).click()
  await expect(painted(6)).toBeVisible()
  await page.getByRole("button", { name: undoCopy.redoNamed["delete-element"], exact: true }).click()
  await expect(element(6)).toHaveCount(0)
  await page.getByRole("button", { name: undoCopy.undoNamed["delete-element"], exact: true }).click()
  await expect(painted(6)).toBeVisible()
  await capture("shape-undone")
  const order = async () => (await post(deckRoutes.open, { deck }, cookie)).json.register.order
  await expect
    .poll(async () => (await order()).filter((row) => row.slide === "element-add").map((row) => row.geometry))
    .toEqual(["rect", "ellipse", "line"])
  await page.reload()
  await expect(page.locator(".thin-page")).toHaveAttribute("data-deck-ready", deck)
  for (const shape of [4, 5, 6]) await expect(painted(shape)).toBeVisible()
  const downloading = page.waitForEvent("download")
  await page.getByRole("button", { name: "Export", exact: true }).click()
  await expect(page.getByRole("dialog", { name: "Export" }).getByRole("button", { name: "Export" })).toBeFocused()
  await page.keyboard.press("Enter")
  const out = path.dirname(await capture("exported"))
  const exported = path.join(out, "shape-insert.pptx")
  await (await downloading).saveAs(exported)
  await page.goto("/")
  await page.locator("input[type=file]").setInputFiles(exported)
  await expect(page).toHaveURL(/\/deck\/[A-Za-z0-9_-]{1,64}$/)
  for (const shape of [4, 5, 6]) await expect(painted(shape)).toBeVisible()
  await capture("reimported")
  note(
    `Shapes opened the tray; Rectangle, Ellipse and Line each painted at once and closed it. The rectangle moved with Shift+ArrowRight and grew from its corner grip; the line was deleted, brought back by Undo, deleted by Redo and brought back again. The server's order held three element-add rows with geometry rect, ellipse and line; a reload painted all three, the export ${path.basename(exported)} downloaded, and a new import of it painted all three.`,
  )
}
